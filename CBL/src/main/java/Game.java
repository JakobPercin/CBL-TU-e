    static void loadTextures() {
        Map<Character, String> textureFiles = Map.ofEntries(
        Map.entry('@', "textures/goldfish.png"),
        Map.entry('#', "textures/wall.png"),
        Map.entry('.', "textures/floor.png"),
        Map.entry('E', "textures/enemy.png"),
        Map.entry('+', "textures/item.png"),
        Map.entry('K', "textures/key.png"),
        Map.entry('D', "textures/door.png"),
        Map.entry('S', "textures/sword.png"),
        Map.entry('O', "textures/shield.png"),
        Map.entry(' ', "textures/fog.png"),
        Map.entry('v', "textures/arrow_down.png"),
        Map.entry('^', "textures/arrow_up.png"),
        Map.entry('<', "textures/arrow_left.png"),
        Map.entry('>', "textures/arrow_right.png")
);

        Map<Character, Color> fallbackColors = Map.ofEntries(
            Map.entry('@', Color.BLUE),
            Map.entry('#', Color.DARK_GRAY),
            Map.entry('.', Color.LIGHT_GRAY),
            Map.entry('E', Color.RED),
            Map.entry('+', Color.GREEN),
            Map.entry('K', Color.YELLOW),
            Map.entry('D', Color.MAGENTA),
            Map.entry('S', Color.ORANGE),
            Map.entry('O', Color.CYAN),
            Map.entry(' ', Color.BLACK)
        );
                                                                                                            
        for (Map.Entry<Character, String> entry : textureFiles.entrySet()) {
            char key = entry.getKey();
            BufferedImage img = null;
            try {
                File file = new File(entry.getValue());
                if (file.exists()) {
                    img = ImageIO.read(file);
                }
            } catch (IOException ignored) {}

            // Fallback generated if PNG file is missing
            if (img == null) {
                img = createFallbackTile(fallbackColors.getOrDefault(key, Color.GRAY), String.valueOf(key));
            }
            textures.put(key, img);
        }
    }

    private static BufferedImage createFallbackTile(Color c, String symbol) {
        BufferedImage img = new BufferedImage(TILE_SIZE, TILE_SIZE, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = img.createGraphics();
        g.setColor(c);
        g.fillRect(0, 0, TILE_SIZE, TILE_SIZE);
        g.setColor(Color.WHITE);
        g.drawRect(0, 0, TILE_SIZE - 1, TILE_SIZE - 1);
        g.setFont(new Font(Font.MONOSPACED, Font.BOLD, 32));
        g.drawString(symbol, TILE_SIZE / 3, (TILE_SIZE * 2) / 3);
        g.dispose();
        return img;
    }

    static void loadLevel() {
        String[] lines = LEVEL.split("\n");
        map = new char[lines.length][];
        seen = new boolean[lines.length][];
        enemyHp = new int[lines.length][];
        for (int r = 0; r < lines.length; r++) {
            map[r] = lines[r].toCharArray();
            seen[r] = new boolean[map[r].length];
            enemyHp[r] = new int[map[r].length];
            for (int ec = 0; ec < map[r].length; ec++)
                if (map[r][ec] == 'E') enemyHp[r][ec] = ENEMY_HEALTH;

            int c = lines[r].indexOf('@');
            if (c >= 0) {
                row = r;
                col = c;
                map[r][c] = '.';
            }
        }
    }

    static int attackPower() {
        return BASE_ATTACK + swords;
    }

    static int damageTaken() {
        return Math.max(MIN_DAMAGE, ENEMY_DAMAGE - shields);
    }

    static void turn(KeyEvent e) {
        if (health <= 0 || won) return;
        int keyCode = e.getKeyCode();
        char keyChar = Character.toLowerCase(e.getKeyChar());

        if (keyChar == 'w' || keyCode == KeyEvent.VK_UP) move(-1, 0);
        else if (keyChar == 's' || keyCode == KeyEvent.VK_DOWN) move(1, 0);
        else if (keyChar == 'a' || keyCode == KeyEvent.VK_LEFT) move(0, -1);
        else if (keyChar == 'd' || keyCode == KeyEvent.VK_RIGHT) move(0, 1);
        else if (Character.isDigit(keyChar)) useItem(keyChar - '1');
        else return;
        if (!won) moveEnemies();
        draw();
    }

    static char cellAt(int r, int c) {
        if (r < 0 || r >= map.length || c < 0 || c >= map[r].length || map[r][c] == ' ') return '#';
        return map[r][c];
    }

    static void move(int dRow, int dCol) {
        int r = row + dRow, c = col + dCol;
        char cell = cellAt(r, c);
        if (cell == '#') return;
        if (cell == 'E') {
            enemyHp[r][c] -= attackPower();
            if (enemyHp[r][c] <= 0) {
                map[r][c] = '.';
                enemyHp[r][c] = 0;
            } else {
                health -= damageTaken(); // enemy survived, hits back
            }
            return;
        }
        if (cell == '+') {
            inventory.add("resit");
            map[r][c] = '.';
        }
        if (cell == 'S') {
            swords++;
            map[r][c] = '.';
        }
        if (cell == 'O') {
            shields++;
            map[r][c] = '.';
        }
        if (cell == 'K') {
            keys++;
            map[r][c] = '.';
        }
        if (cell == 'D' && keys < KEYS) return;
        if (cell == 'D') won = true;
        row = r;
        col = c;
    }

    static void useItem(int slot) {
        if (slot < 0 || slot >= inventory.size()) return;
        inventory.remove(slot);
        health = Math.min(MAX_HEALTH, health + RESIT_HEAL);
    }

    static void moveEnemies() {
        ArrayList<int[]> enemies = new ArrayList<>();
        for (int r = 0; r < map.length; r++)
            for (int c = 0; c < map[r].length; c++)
                if (map[r][c] == 'E') enemies.add(new int[] {r, c});
        int[][] steps = {{-1, 0}, {1, 0}, {0, -1}, {0, 1}};
        for (int[] enemy : enemies) {
            int[] step = steps[random.nextInt(4)];
            int dRow = row - enemy[0], dCol = col - enemy[1];
            if (Math.abs(dRow) <= SIGHT && Math.abs(dCol) <= SIGHT && random.nextBoolean())
                step = Math.abs(dRow) > Math.abs(dCol) ? steps[dRow < 0 ? 0 : 1] : steps[dCol < 0 ? 2 : 3];
            int r = enemy[0] + step[0], c = enemy[1] + step[1];
            if (r == row && c == col) health -= damageTaken();
            else if (cellAt(r, c) == '.') {
                map[enemy[0]][enemy[1]] = '.';
                map[r][c] = 'E';
                enemyHp[r][c] = enemyHp[enemy[0]][enemy[1]];
                enemyHp[enemy[0]][enemy[1]] = 0;
            }
        }
    }

    static void draw() {
        if (screen != null) {
            screen.repaint();
        }
    }

    static class GamePanel extends JPanel {
        private final int hudHeight = 60;

        public GamePanel() {
            int width = (VIEW_COLS * 2 + 1) * TILE_SIZE;
            int height = (VIEW_ROWS * 2 + 1) * TILE_SIZE + hudHeight;
            setPreferredSize(new Dimension(width, height));
            setBackground(Color.BLACK);
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);

            int viewWidth = VIEW_COLS * 2 + 1;
            int viewHeight = VIEW_ROWS * 2 + 1;

            // 1. Render Map Tiles
            for (int vr = 0; vr < viewHeight; vr++) {
                for (int vc = 0; vc < viewWidth; vc++) {
                    int r = row - VIEW_ROWS + vr;
                    int c = col - VIEW_COLS + vc;

                    boolean inMap = r >= 0 && r < map.length && c >= 0 && c < map[r].length;
                    boolean near = Math.abs(r - row) <= SIGHT && Math.abs(c - col) <= SIGHT;

                    if (inMap && near) seen[r][c] = true;

                    char tileChar = ' ';
                    if (r == row && c == col) {
                        tileChar = '@';
                    } else if (inMap && seen[r][c]) {
                        if (map[r][c] == 'E' && !near) {
                            tileChar = '.';
                        } else {
                            tileChar = map[r][c];
                        }
                    }

                    if (tileChar != '#' && tileChar != ' ') {
                        BufferedImage floorImg = textures.get('.');
                        if (floorImg != null) {
                            g.drawImage(floorImg, vc * TILE_SIZE, vr * TILE_SIZE, TILE_SIZE, TILE_SIZE, null);
                        }
                    }

                    BufferedImage img = textures.getOrDefault(tileChar, textures.get(' '));
                    if (img != null) {
                        g.drawImage(img, vc * TILE_SIZE, vr * TILE_SIZE, TILE_SIZE, TILE_SIZE, null);
                    }
                }
            }

            g.setColor(Color.DARK_GRAY);
            int yHudStart = viewHeight * TILE_SIZE;
            g.fillRect(0, yHudStart, getWidth(), hudHeight);

            g.setColor(Color.WHITE);
            g.setFont(new Font(Font.SANS_SERIF, Font.BOLD, 14));

            StringBuilder status = new StringBuilder();
            status.append("ECTS ").append(Math.max(0, health)).append("/").append(MAX_HEALTH)
                  .append("  |  Keys ").append(keys).append("/").append(KEYS)
                  .append("  |  ATK ").append(attackPower())
                  .append("  |  DEF ").append(shields)
                  .append("  |  Items:");
            for (int i = 0; i < inventory.size(); i++) {
                status.append(" ").append(i + 1).append("=").append(inventory.get(i));
            }
            g.drawString(status.toString(), 15, yHudStart + 25);

            String message;
            if (won) {
                g.setColor(Color.GREEN);
                message = "You reached the door!";
            } else if (health <= 0) {
                g.setColor(Color.RED);
                message = "You died.";
            } else {
                g.setColor(Color.LIGHT_GRAY);
                message = "Use WASD or arrow keys to move | Use item: Number key (1-9)";
            }
            g.drawString(message, 15, yHudStart + 48);
        }
    }
